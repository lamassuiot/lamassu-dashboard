'use client';

import { RadioGroup as RadioGroupPrimitive } from 'radix-ui';

import { Label } from '@/components/ui/label';
import { SERVER_KEYGEN_SPECS, type ServerKeygenType } from '@/lib/ra-form';
import { RaFormSection, SettingToggleGroup } from './RaFormSection';
import type { RaSectionProps } from './types';

const KEY_TYPES: readonly ServerKeygenType[] = ['ECDSA', 'RSA'];

export function KeygenSection({ values, update }: RaSectionProps) {
  const { serverKeygen } = values;
  const setKeygen = (patch: Partial<typeof serverKeygen>) => update({ serverKeygen: { ...serverKeygen, ...patch } });
  const selectedHint = SERVER_KEYGEN_SPECS[serverKeygen.type].find(spec => spec.value === serverKeygen.spec)?.hint;

  return (
    <RaFormSection
      id="keygen"
      title="Server-side key generation"
      description="Let constrained devices request a key pair generated by the platform (EST serverkeygen)."
    >
      <SettingToggleGroup
        id="enableKeyGeneration"
        label="Enable server-side key generation"
        description="The private key is generated on the server and returned to the device with its certificate."
        checked={serverKeygen.enabled}
        onCheckedChange={enabled => setKeygen({ enabled })}
      >
        <div className="space-y-3">
          <Label id="serverKeygenKey-label">Key type</Label>
          {/* One radio group for algorithm and size, so the pair can never be inconsistent. */}
          <RadioGroupPrimitive.Root
            value={`${serverKeygen.type}:${serverKeygen.spec}`}
            onValueChange={value => {
              const [type, spec] = value.split(':') as [ServerKeygenType, string];
              setKeygen({ type, spec });
            }}
            aria-labelledby="serverKeygenKey-label"
            aria-describedby={selectedHint ? 'serverKeygenKey-hint' : undefined}
            className="grid grid-cols-[3.5rem_1fr] items-center gap-x-4 gap-y-2"
          >
            {KEY_TYPES.map(type => (
              <div key={type} className="contents">
                <span className="text-xs font-medium text-muted-foreground">{type}</span>
                <div className="flex flex-wrap gap-2">
                  {SERVER_KEYGEN_SPECS[type].map(spec => (
                    <RadioGroupPrimitive.Item
                      key={spec.value}
                      value={`${type}:${spec.value}`}
                      aria-label={`${type} ${spec.label}`}
                      className="h-8 min-w-20 rounded-md border px-3 text-sm transition-colors outline-none hover:bg-muted focus-visible:ring-3 focus-visible:ring-ring/30 data-[state=checked]:border-primary data-[state=checked]:bg-primary/10 data-[state=checked]:font-medium data-[state=checked]:text-primary"
                    >
                      {spec.label}
                    </RadioGroupPrimitive.Item>
                  ))}
                </div>
              </div>
            ))}
          </RadioGroupPrimitive.Root>
          {selectedHint && <p id="serverKeygenKey-hint" className="text-xs text-muted-foreground">{selectedHint}</p>}
        </div>
      </SettingToggleGroup>
    </RaFormSection>
  );
}
